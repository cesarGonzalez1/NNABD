-- Relación NNA ↔ Tutor
-- Un NNA puede cambiar de tutor a lo largo del tiempo.
-- principal=TRUE indica el tutor vigente; solo puede haber uno por NNA (UniqueConstraint parcial).
-- El registro anterior se cierra poniendo principal=FALSE y registrando fecha_fin.
CREATE TABLE web_nnatutor (
    id            bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nna_id        bigint NOT NULL,
    tutor_id      bigint NOT NULL,
    parentesco    varchar(30) NOT NULL DEFAULT '',
    principal     boolean     NOT NULL DEFAULT FALSE,
    fecha_inicio  date NULL,
    fecha_fin     date NULL,
    observaciones text NOT NULL DEFAULT ''
    -- La unicidad "solo un tutor principal por NNA" se implementa con índice parcial (ver sección índices)
);

-- Relación NNA ↔ Equipo Multidisciplinario (historial)
-- Un NNA puede cambiar de equipo a lo largo del tiempo.
-- activo=TRUE indica el equipo vigente; solo puede haber uno por NNA (UniqueConstraint parcial).
-- El registro anterior se cierra poniendo activo=FALSE y registrando fecha_fin.
CREATE TABLE web_nnaequipo (
    id            bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nna_id        bigint NOT NULL,
    equipo_id     bigint NOT NULL,
    fecha_inicio  date   NOT NULL,
    fecha_fin     date   NULL,
    activo        boolean NOT NULL DEFAULT TRUE,
    motivo_cambio text    NOT NULL DEFAULT ''
);

