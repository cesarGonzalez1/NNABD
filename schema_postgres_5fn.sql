-- ---------------------------------------------------------------------------
-- IDIOMAS
-- Los idiomas de NNA, tutores y empleados son OPCIONALES (0..N por persona).
-- No existe restricción de mínimo; una persona puede no tener idiomas registrados.
-- El campo "variante" en web_idiomanna captura la variante específica del NNA
-- como texto libre (p. ej. "Náhuatl de la Huasteca") sin necesidad de catálogo.
-- ---------------------------------------------------------------------------

CREATE TABLE web_idiomanna (
    id                   bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nna_id               bigint NOT NULL,
    lengua_id            bigint NOT NULL,
    variante             varchar(200) NOT NULL DEFAULT '',  -- variante específica que habla el NNA
    nivel                varchar(20)  NOT NULL,
    nivel_competencia_id bigint NULL,
    modo_adquisicion_id  bigint NULL,
    es_lengua_materna    boolean NOT NULL,
    preferente           boolean NOT NULL,
    autodenominacion     varchar(200) NOT NULL
);

CREATE TABLE web_idiomatutor (
    id                   bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tutor_id             bigint NOT NULL,
    lengua_id            bigint NOT NULL,
